/** Puntos [x, y] de una función muestreada (para gráficas calculadas con un modelo). */
const muestrear = (desde: number, hasta: number, paso: number, f: (x: number) => number, dec = 2): [number, number][] => {
  const out: [number, number][] = [];
  const n = Math.round((hasta - desde) / paso);
  for (let i = 0; i <= n; i++) {
    const x = Number((desde + i * paso).toFixed(4));
    const y = Number(f(x).toFixed(dec));
    out.push([x, Object.is(y, -0) ? 0 : y]);
  }
  return out;
};

